#!/usr/bin/env node
/* Build script.
 *
 *   node build.js            → everything in dist/
 *   node build.js --framer   → only the Framer component (+ standalone preview)
 *
 * Outputs (all generated from src/data.js, so they can't drift apart):
 *   dist/InsurerPhoneFinder.framer.tsx  Framer code component (self-contained)
 *   dist/insurer-finder.html            the same built page, for previewing in a browser
 *   dist/insurer-table.html             crawlable table, grouped by insurer
 *   dist/insurer-routes.csv             one row per route, for a Framer CMS import
 */
"use strict";
var fs = require("fs");
var path = require("path");

var ROOT = __dirname;
var DIST = path.join(ROOT, "dist");
var LOGO_DIR = path.join(ROOT, "assets", "logos");

function read(rel) { return fs.readFileSync(path.join(ROOT, rel), "utf8"); }

function freshEngine() {
  // Always read the current files (tests may call the build repeatedly).
  delete require.cache[require.resolve("./src/data.js")];
  delete require.cache[require.resolve("./src/engine.js")];
  return require("./src/engine.js");
}

function escapeHtml(s) {
  return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

function stripDebug(html) {
  return html
    .replace(/<!-- DEBUG:START -->[\s\S]*?<!-- DEBUG:END -->\s*/g, "")
    .replace(/\/\* DEBUG:START \*\/[\s\S]*?\/\* DEBUG:END \*\/\s*/g, "");
}

function inlineScript(code) { return "<script>\n" + code.replace(/<\/script/gi, "<\\/script") + "\n</script>"; }

function loadLogos(data) {
  var logos = {}, missing = [];
  data.insurers.forEach(function (ins) {
    var found = false;
    [["svg", "image/svg+xml"], ["png", "image/png"]].forEach(function (pair) {
      if (found) return;
      var file = path.join(LOGO_DIR, ins.id + "." + pair[0]);
      if (fs.existsSync(file)) {
        logos[ins.id] = "data:" + pair[1] + ";base64," + fs.readFileSync(file).toString("base64");
        found = true;
      }
    });
    if (!found) missing.push(ins.id);
  });
  return { logos: logos, missing: missing };
}

// ----------------------------------------------------------------- page
function buildPage() {
  var E = freshEngine();
  var html = stripDebug(read("index.html"));
  var logoInfo = loadLogos(E.DATA);
  var boot = "window.__IPF_LOGOS__ = " + JSON.stringify(logoInfo.logos) + ";\n" +
             "window.__IPF_INITIAL_QUERY__ = \"__IPF_INITIAL_QUERY__\";";
  var dataTag = '<script src="src/data.js"></script>';
  var engineTag = '<script src="src/engine.js"></script>';
  if (html.indexOf(dataTag) === -1 || html.indexOf(engineTag) === -1) throw new Error("index.html script tags not found");
  html = html.replace(dataTag, function () { return inlineScript(boot) + "\n" + inlineScript(read("src/data.js")); });
  html = html.replace(engineTag, function () { return inlineScript(read("src/engine.js")); });
  return { html: html, missingLogos: logoInfo.missing };
}

// ----------------------------------------------------------------- framer
function buildFramer(pageHtml) {
  var E = freshEngine();
  var b64 = Buffer.from(pageHtml, "utf8").toString("base64");
  return [
    "// Insurer Phone Finder: Framer code component.",
    "// GENERATED by build.js from index.html + src/data.js. Do not edit by hand: edit the source and run `npm run build`.",
    "// Last checked: " + E.DATA.lastChecked,
    'import { useEffect, useRef, useState } from "react"',
    'import { addPropertyControls, ControlType, RenderTarget } from "framer"',
    "",
    "const HTML_BASE64 = " + JSON.stringify(b64),
    "",
    "// URL parameters the tool owns. Only these are ever written to the page URL.",
    "const STATE_KEYS = " + JSON.stringify(E.STATE_KEYS),
    "",
    "function decodeHtml(): string {",
    "    const bin = atob(HTML_BASE64)",
    "    const bytes = new Uint8Array(bin.length)",
    "    for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i)",
    '    return new TextDecoder("utf-8").decode(bytes)',
    "}",
    "",
    "function isCanvas(): boolean {",
    "    try {",
    "        return RenderTarget.current() === RenderTarget.canvas",
    "    } catch (e) {",
    "        return false",
    "    }",
    "}",
    "",
    "function readParentSearch(): string {",
    "    try {",
    '        return window.location.search || ""',
    "    } catch (e) {",
    '        return ""',
    "    }",
    "}",
    "",
    "function writeParentUrl(params: Record<string, unknown>) {",
    "    try {",
    "        const url = new URL(window.location.href)",
    "        STATE_KEYS.forEach((k) => url.searchParams.delete(k))",
    "        STATE_KEYS.forEach((k) => {",
    "            const v = params ? params[k] : undefined",
    '            if (typeof v === "string" && /^[A-Za-z0-9_-]{1,40}$/.test(v)) url.searchParams.set(k, v)',
    "        })",
    "        if (url.href !== window.location.href) {",
    '            window.history.replaceState(window.history.state, "", url.href)',
    "        }",
    "    } catch (e) {",
    "        // Fail silently: the tool keeps working without URL sync.",
    "    }",
    "}",
    "",
    "/**",
    " * @framerSupportedLayoutWidth any",
    " * @framerSupportedLayoutHeight auto",
    " * @framerIntrinsicWidth 640",
    " * @framerIntrinsicHeight 720",
    " */",
    "export default function InsurerPhoneFinder(props: { syncUrl?: boolean; style?: Record<string, any> }) {",
    "    const { syncUrl = true, style } = props",
    "    const frameRef = useRef<HTMLIFrameElement>(null)",
    "    const [height, setHeight] = useState(720)",
    "    const [srcDoc, setSrcDoc] = useState<string | null>(null)",
    "",
    "    // Build the page after mount (keeps server rendering and hydration consistent).",
    "    useEffect(() => {",
    "        let search = \"\"",
    "        if (syncUrl && !isCanvas()) search = readParentSearch()",
    "        let html = \"\"",
    "        try {",
    "            html = decodeHtml()",
    "        } catch (e) {",
    "            return",
    "        }",
    '        const injected = JSON.stringify(search).replace(/</g, "\\\\u003c")',
    '        setSrcDoc(html.replace(\'"__IPF_INITIAL_QUERY__"\', () => injected))',
    "    }, [syncUrl])",
    "",
    "    useEffect(() => {",
    "        function onMessage(event: MessageEvent) {",
    "            const frame = frameRef.current",
    "            if (!frame || event.source !== frame.contentWindow) return",
    "            const data = event.data",
    '            if (!data || typeof data !== "object") return',
    '            if (data.type === "insurer-finder-height") {',
    "                const h = Number(data.height)",
    "                if (isFinite(h) && h > 0) setHeight(Math.ceil(h))",
    '            } else if (data.type === "insurer-finder-state") {',
    "                if (syncUrl && !isCanvas()) writeParentUrl(data.params)",
    "            }",
    "        }",
    "        try {",
    '            window.addEventListener("message", onMessage)',
    "        } catch (e) {",
    "            return",
    "        }",
    "        return () => {",
    "            try {",
    '                window.removeEventListener("message", onMessage)',
    "            } catch (e) {}",
    "        }",
    "    }, [syncUrl])",
    "",
    "    return (",
    '        <div style={{ ...style, width: "100%", height }}>',
    "            {srcDoc !== null && (",
    "                <iframe",
    "                    ref={frameRef}",
    '                    title="Insurer phone finder"',
    "                    srcDoc={srcDoc}",
    '                    sandbox="allow-scripts allow-popups allow-popups-to-escape-sandbox allow-top-navigation-by-user-activation"',
    '                    allow="clipboard-write"',
    '                    style={{ width: "100%", height, border: 0, display: "block", background: "transparent" }}',
    "                />",
    "            )}",
    "        </div>",
    "    )",
    "}",
    "",
    "addPropertyControls(InsurerPhoneFinder, {",
    "    syncUrl: {",
    "        type: ControlType.Boolean,",
    '        title: "Sync URL",',
    "        defaultValue: true,",
    '        enabledTitle: "On",',
    '        disabledTitle: "Off",',
    '        description: "Copy the current step to the page URL (e.g. ?insurer=axa&query=preauth) so results can be shared.",',
    "    },",
    "})",
    ""
  ].join("\n");
}

// ----------------------------------------------------------------- table + CSV rows
function routeRows() {
  var E = freshEngine();
  return E.allRoutes().map(function (x) {
    var r = x.result, m = r.main;
    var notes = [];
    if (r.covers) notes.push("This line handles: " + r.covers + ".");
    r.tips.forEach(function (t) { notes.push(t); });
    var alts = r.alternatives.map(function (a) {
      return (a.label ? a.label + ": " : "") + a.number +
        (a.menu.length ? " (" + a.menu.join(", then ") + ")" : "") +
        (a.hoursText ? ", " + a.hoursText : "");
    });
    return {
      routeId: r.routeId,
      insurerId: r.insurerId,
      insurer: r.insurerName,
      query: x.labels.query,
      followUp: x.labels.followUp,
      number: m.number,
      tel: m.tel,
      team: m.team,
      menu: m.menu.length ? m.menu.join(", then ") : "No menu options listed",
      hours: m.hoursText,
      tips: notes,
      alternatives: alts
    };
  });
}

function buildTable() {
  var E = freshEngine(), D = E.DATA, rows = routeRows();
  var out = [];
  out.push("<!-- Insurer phone numbers table. GENERATED by build.js from src/data.js. Do not edit by hand. -->");
  out.push('<section class="ipf-table">');
  out.push("<style>.ipf-table{font-family:inherit;line-height:1.45}.ipf-table table{border-collapse:collapse;width:100%;margin:0 0 28px}.ipf-table caption{text-align:left;font-weight:600;padding:0 0 6px}.ipf-table th,.ipf-table td{border:1px solid #d3d8de;padding:8px 10px;text-align:left;vertical-align:top}.ipf-table thead th{background:#f5f6f8}.ipf-table h2{margin:28px 0 8px}</style>");
  out.push('<p class="ipf-table-checked"><strong>Last checked: ' + escapeHtml(D.lastChecked) + "</strong> · " + escapeHtml(D.disclaimer) + "</p>");
  D.insurers.forEach(function (ins) {
    var mine = rows.filter(function (r) { return r.insurerId === ins.id; });
    out.push('<h2 id="insurer-' + escapeHtml(ins.id) + '">' + escapeHtml(ins.name) + " provider phone numbers</h2>");
    out.push('<table data-insurer="' + escapeHtml(ins.id) + '">');
    out.push("<caption>" + escapeHtml(ins.name) + ": which number to call and which phone-menu options to choose</caption>");
    out.push('<thead><tr><th scope="col">What you need</th><th scope="col">Details</th><th scope="col">Number</th><th scope="col">Phone menu</th><th scope="col">Opening hours</th><th scope="col">Tips</th></tr></thead>');
    out.push("<tbody>");
    mine.forEach(function (r) {
      var numberCell = '<a href="' + escapeHtml(r.tel) + '">' + escapeHtml(r.number) + "</a>" + (r.team ? "<br>" + escapeHtml(r.team) : "");
      var tips = r.tips.slice();
      r.alternatives.forEach(function (a) { tips.push("Other " + r.insurer + " line: " + a); });
      var tipsCell = tips.length ? "<ul>" + tips.map(function (t) { return "<li>" + escapeHtml(t) + "</li>"; }).join("") + "</ul>" : "";
      out.push('<tr data-route="' + escapeHtml(r.routeId) + '">' +
        '<th scope="row">' + escapeHtml(r.query) + "</th>" +
        "<td>" + escapeHtml(r.followUp) + "</td>" +
        "<td>" + numberCell + "</td>" +
        "<td>" + escapeHtml(r.menu) + "</td>" +
        "<td>" + escapeHtml(r.hours) + "</td>" +
        "<td>" + tipsCell + "</td></tr>");
    });
    out.push("</tbody>");
    out.push("</table>");
  });
  out.push("<p>Last checked: " + escapeHtml(D.lastChecked) + " · " + escapeHtml(D.disclaimer) + "</p>");
  out.push("</section>");
  return out.join("\n") + "\n";
}

function csvCell(v) {
  var s = String(v === undefined || v === null ? "" : v);
  return /[",\r\n]/.test(s) ? '"' + s.replace(/"/g, '""') + '"' : s;
}

var CSV_COLUMNS = ["slug", "insurer", "query", "follow_up", "number", "team", "menu_path", "hours", "tips", "alternative", "last_checked"];

function buildCsv() {
  var E = freshEngine(), rows = routeRows();
  var lines = [CSV_COLUMNS.join(",")];
  rows.forEach(function (r) {
    lines.push([r.routeId, r.insurer, r.query, r.followUp, r.number, r.team, r.menu, r.hours,
      r.tips.join(" "), r.alternatives.join("; "), E.DATA.lastChecked].map(csvCell).join(","));
  });
  return lines.join("\r\n") + "\r\n";
}

// ----------------------------------------------------------------- main
function buildAll(opts) {
  opts = opts || {};
  var page = buildPage();
  var result = { page: page.html, framer: buildFramer(page.html), missingLogos: page.missingLogos };
  if (!opts.framerOnly) { result.table = buildTable(); result.csv = buildCsv(); }
  return result;
}

module.exports = { buildAll: buildAll, buildPage: buildPage, buildFramer: buildFramer, buildTable: buildTable, buildCsv: buildCsv, routeRows: routeRows, CSV_COLUMNS: CSV_COLUMNS, stripDebug: stripDebug };

if (require.main === module) {
  var framerOnly = process.argv.indexOf("--framer") !== -1;
  var out = buildAll({ framerOnly: framerOnly });
  fs.mkdirSync(DIST, { recursive: true });
  fs.writeFileSync(path.join(DIST, "InsurerPhoneFinder.framer.tsx"), out.framer);
  fs.writeFileSync(path.join(DIST, "insurer-finder.html"), out.page);
  console.log("✓ dist/InsurerPhoneFinder.framer.tsx (" + Math.round(out.framer.length / 1024) + " KB)");
  console.log("✓ dist/insurer-finder.html");
  if (!framerOnly) {
    fs.writeFileSync(path.join(DIST, "insurer-table.html"), out.table);
    fs.writeFileSync(path.join(DIST, "insurer-routes.csv"), out.csv);
    console.log("✓ dist/insurer-table.html");
    console.log("✓ dist/insurer-routes.csv");
  }
  if (out.missingLogos.length) {
    console.log("ℹ No logo file yet (using initials) for: " + out.missingLogos.join(", ") +
      ". Add assets/logos/<id>.svg or .png and rebuild.");
  }
}
